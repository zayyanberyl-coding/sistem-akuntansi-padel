-- =====================================================================
--  A. PENGGUNA & PERAN
--  Akun login dibuat di Supabase > Authentication > Users.
--  Tabel ini memberi PERAN pada akun tersebut:
--    owner : semua akses (termasuk tarif, stok, paket, refund)
--    admin : operasional harian (booking, pembayaran, sewa, member)
--  Akun login yang tidak ada di tabel ini TIDAK bisa melihat data apa pun.
-- =====================================================================
create table pengguna (
  id          uuid primary key references auth.users(id) on delete cascade,
  nama        text not null,
  peran       text not null check (peran in ('owner', 'admin')),
  created_at  timestamptz not null default now()
);

-- Peran pengguna yang sedang login (null jika belum login / tidak terdaftar).
-- "security definer" supaya bisa dipakai di policy tanpa berputar-putar (rekursi).
create or replace function peran_saya() returns text
language sql stable security definer set search_path = public as $$
  select peran from pengguna where id = auth.uid();
$$;


-- =====================================================================
--  B. TABEL MASTER (data pokok)
-- =====================================================================

-- 1. LAPANGAN: daftar lapangan padel beserta tarif per jam
create table lapangan (
  id            bigint generated by default as identity primary key,
  nama          text not null unique,
  jenis         text not null default 'indoor' check (jenis in ('indoor', 'outdoor')),
  tarif_normal  numeric(14,2) not null check (tarif_normal >= 0),  -- tarif per jam di luar prime time
  tarif_prime   numeric(14,2) not null check (tarif_prime  >= 0),  -- tarif per jam saat prime time
  aktif         boolean not null default true
);

-- 2. PELANGGAN: orang yang menyewa lapangan / membeli paket member
--    (berisi data pribadi -> hanya bisa dibaca pengguna yang login)
create table pelanggan (
  id              bigint generated by default as identity primary key,
  nama            text not null,
  no_hp           text,
  email           text,
  tanggal_daftar  date not null default current_date
);

-- 3. PAKET_MEMBER: jenis paket jam main yang dijual (dibayar di muka)
create table paket_member (
  id                 bigint generated by default as identity primary key,
  nama_paket         text not null unique,
  jumlah_jam         int  not null check (jumlah_jam > 0),
  harga              numeric(14,2) not null check (harga >= 0),
  masa_berlaku_hari  int  not null default 30 check (masa_berlaku_hari > 0),
  aktif              boolean not null default true
);

-- 4. AKUN: bagan akun (Chart of Accounts)
--    saldo_normal 'D' = bertambah di Debit, 'K' = bertambah di Kredit
create table akun (
  kode          text primary key,
  nama          text not null,
  kategori      text not null check (kategori in ('Aset', 'Kewajiban', 'Ekuitas', 'Pendapatan', 'Beban')),
  saldo_normal  char(1) not null check (saldo_normal in ('D', 'K'))
);

-- 5. PERALATAN: raket & bola yang bisa disewa
create table peralatan (
  id           bigint generated by default as identity primary key,
  nama         text not null unique,
  jenis        text not null check (jenis in ('raket', 'bola')),
  tarif_sewa   numeric(14,2) not null check (tarif_sewa  >= 0),        -- per unit per booking
  denda_rusak  numeric(14,2) not null default 0 check (denda_rusak >= 0), -- denda per unit rusak
  stok         int not null default 0 check (stok >= 0)                -- stok tidak boleh minus
);


-- =====================================================================
--  C. TABEL TRANSAKSI
--  Kolom "dibuat_oleh" diisi otomatis dengan id pengguna yang login
--  (jejak audit: siapa yang mencatat transaksi).
--  id tabel transaksi & akuntansi memakai "generated ALWAYS": nomor urut
--  selalu dibuat database, tidak bisa diisi dari aplikasi. (Data contoh di
--  seed.sql memakai "overriding system value" untuk menulis id tetap.)
-- =====================================================================

-- 6. PEMBELIAN_PAKET: pelanggan membeli paket member
--    harga, jam_total, tanggal_kadaluarsa DIISI OTOMATIS oleh trigger.
--    breakage_diakui = sisa nilai paket kedaluwarsa sudah diakui pendapatan.
create table pembelian_paket (
  id                  bigint generated always as identity primary key,
  pelanggan_id        bigint not null references pelanggan(id),
  paket_id            bigint not null references paket_member(id),
  tanggal_beli        date not null default current_date,
  tanggal_kadaluarsa  date,
  harga               numeric(14,2),
  jam_total           int,
  jam_terpakai        int not null default 0 check (jam_terpakai >= 0),
  metode_bayar        text not null default 'tunai' check (metode_bayar in ('tunai', 'transfer', 'qris')),
  breakage_diakui     boolean not null default false,
  nilai_breakage      numeric(14,2) not null default 0,
  dibuat_oleh         uuid default auth.uid(),
  check (jam_terpakai <= jam_total)
);

-- 7. BOOKING: pemesanan lapangan
--    kode_booking, durasi_jam, jenis_tarif, total_harga, status awal
--    DIISI OTOMATIS oleh trigger (lihat triggers.sql)
--    Alur status: menunggu -> dp -> lunas -> selesai
--                 (bisa 'batal' selama belum selesai)
--    Saat batal, trigger menentukan hasil_batal:
--      'refund'     -> uang dikembalikan (batal oleh klub / >= 24 jam sebelum main)
--      'hangus'     -> uang yang sudah dibayar menjadi pendapatan lain-lain
--      'tanpa_dana' -> belum ada pembayaran / booking paket member
create table booking (
  id                    bigint generated always as identity primary key,
  kode_booking          text unique,
  pelanggan_id          bigint not null references pelanggan(id),
  lapangan_id           bigint not null references lapangan(id),
  tanggal               date not null,
  jam_mulai             time not null,
  jam_selesai           time not null,
  durasi_jam            int,
  jenis_tarif           text check (jenis_tarif in ('normal', 'prime', 'campuran', 'member')),
  total_harga           numeric(14,2) not null default 0,
  pembelian_paket_id    bigint references pembelian_paket(id), -- terisi jika main pakai paket member
  status                text not null default 'menunggu'
                        check (status in ('menunggu', 'dp', 'lunas', 'selesai', 'batal')),
  catatan               text,
  dibatalkan_oleh_klub  boolean not null default false,
  alasan_batal          text,
  hasil_batal           text check (hasil_batal in ('refund', 'hangus', 'tanpa_dana')),
  metode_refund         text check (metode_refund in ('tunai', 'transfer', 'qris')),
  dibuat_oleh           uuid default auth.uid(),
  diubah_oleh           uuid,
  created_at            timestamptz not null default now(),
  check (jam_selesai > jam_mulai)
);

-- 8. PEMBAYARAN: uang yang diterima untuk sebuah booking (DP / pelunasan)
--    kolom "jenis" DIISI OTOMATIS: 'pelunasan' kalau jumlah = sisa tagihan
create table pembayaran (
  id            bigint generated always as identity primary key,
  booking_id    bigint not null references booking(id),
  tanggal       date not null default current_date,
  jenis         text check (jenis in ('dp', 'pelunasan')),
  jumlah        numeric(14,2) not null check (jumlah > 0),
  metode_bayar  text not null default 'tunai' check (metode_bayar in ('tunai', 'transfer', 'qris')),
  dibuat_oleh   uuid default auth.uid(),
  created_at    timestamptz not null default now()
);

-- 9. SEWA_PERALATAN: peralatan yang disewa dalam sebuah booking
--    tarif, subtotal, denda DIISI OTOMATIS dari tabel peralatan
create table sewa_peralatan (
  id                 bigint generated always as identity primary key,
  booking_id         bigint not null references booking(id),
  peralatan_id       bigint not null references peralatan(id),
  jumlah             int not null check (jumlah > 0),
  tarif              numeric(14,2),
  subtotal           numeric(14,2),
  metode_bayar       text not null default 'tunai' check (metode_bayar in ('tunai', 'transfer', 'qris')),
  tanggal_sewa       date not null default current_date,
  status_kembali     text not null default 'dipinjam'
                     check (status_kembali in ('dipinjam', 'dikembalikan', 'rusak')),
  jumlah_rusak       int not null default 0 check (jumlah_rusak >= 0),
  denda              numeric(14,2) not null default 0 check (denda >= 0),
  tanggal_kembali    date,
  dibuat_oleh        uuid default auth.uid(),
  dikembalikan_oleh  uuid,
  check (jumlah_rusak <= jumlah)
);

-- 10. RIWAYAT_STATUS_BOOKING: jejak audit setiap perubahan status booking
--     (diisi trigger; tidak bisa diubah/dihapus dari aplikasi)
create table riwayat_status_booking (
  id            bigint generated always as identity primary key,
  booking_id    bigint not null references booking(id),
  status_lama   text,
  status_baru   text not null,
  keterangan    text,
  oleh          uuid,
  waktu         timestamptz not null default now()
);


-- =====================================================================
--  D. TABEL AKUNTANSI (diisi HANYA oleh trigger, bukan dari aplikasi)
-- =====================================================================

-- 11. JURNAL: header jurnal umum (satu transaksi = satu jurnal)
create table jurnal (
  id           bigint generated always as identity primary key,
  no_bukti     text unique,              -- contoh: JU-00001 (otomatis)
  tanggal      date not null,
  keterangan   text not null,
  sumber       text not null,            -- asal transaksi: pembayaran / booking / pembelian_paket / sewa_peralatan
  sumber_id    bigint,                   -- id baris di tabel sumber
  dibuat_oleh  uuid,                     -- pengguna yang memicu transaksi
  created_at   timestamptz not null default now()
);

-- 12. JURNAL_DETAIL: baris debit & kredit (double-entry)
--     Setiap baris hanya boleh berisi debit ATAU kredit, tidak keduanya.
create table jurnal_detail (
  id         bigint generated always as identity primary key,
  jurnal_id  bigint not null references jurnal(id) on delete cascade,
  akun_kode  text not null references akun(kode),
  debit      numeric(14,2) not null default 0 check (debit  >= 0),
  kredit     numeric(14,2) not null default 0 check (kredit >= 0),
  check ((debit > 0 and kredit = 0) or (kredit > 0 and debit = 0))
);

-- 13. TUTUP_BUKU: bulan yang sudah ditutup (laporannya dikunci).
--     Tanggal di periode ini tidak bisa lagi dipakai transaksi maupun jurnal.
--     Diisi/dihapus HANYA lewat fungsi tutup_periode() & buka_periode().
create table tutup_buku (
  periode       date primary key                       -- tanggal 1 bulan yang ditutup
                check (periode = date_trunc('month', periode)::date),
  ditutup_oleh  uuid,
  ditutup_pada  timestamptz not null default now()
);

-- 14. RIWAYAT_TUTUP_BUKU: jejak audit setiap tutup buku & buka kembali
create table riwayat_tutup_buku (
  id       bigint generated always as identity primary key,
  periode  date not null,
  aksi     text not null check (aksi in ('tutup', 'buka')),
  alasan   text,                                         -- wajib diisi saat buka kembali
  oleh     uuid,
  waktu    timestamptz not null default now()
);

-- 15. SETTLEMENT_QRIS: pencairan Saldo QRIS ke rekening Bank oleh penyedia QRIS.
--     Angka diambil dari laporan settlement / mutasi rekening (dokumen sumber),
--     bukan dihitung dengan persentase, karena aturan MDR bertingkat & bisa berubah.
--     biaya_mdr DIISI OTOMATIS = jumlah_bruto - jumlah_bersih.
--     Hanya owner yang boleh mencatat (pemisahan tugas: penerima uang ≠ pencatat pencairan).
create table settlement_qris (
  id             bigint generated always as identity primary key,
  tanggal        date not null default current_date,       -- tanggal uang masuk ke Bank
  no_referensi   text not null unique,                     -- no. laporan settlement / mutasi (cegah dicatat 2x)
  jumlah_bruto   numeric(14,2) not null check (jumlah_bruto > 0),    -- total pembayaran QRIS yang dicairkan
  jumlah_bersih  numeric(14,2) not null check (jumlah_bersih >= 0),  -- yang masuk ke rekening
  biaya_mdr      numeric(14,2),
  catatan        text,
  dibuat_oleh    uuid default auth.uid(),
  created_at     timestamptz not null default now(),
  check (jumlah_bersih <= jumlah_bruto)
);


