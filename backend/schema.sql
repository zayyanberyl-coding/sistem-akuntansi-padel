-- =====================================================================
--  E. VIEW: "tabel virtual" gabungan supaya query di frontend lebih mudah
--  security_invoker = true -> view tetap mengikuti aturan keamanan (RLS)
-- =====================================================================

-- Booking lengkap + nama pelanggan, lapangan, pembuat, total dibayar & sisa
create view v_booking_lengkap with (security_invoker = true) as
select
  b.*,
  p.nama  as nama_pelanggan,
  p.no_hp as no_hp,
  l.nama  as nama_lapangan,
  u.nama  as nama_pembuat,
  coalesce(bayar.total, 0) as total_dibayar,
  case when b.pembelian_paket_id is not null or b.status = 'batal' then 0
       else b.total_harga - coalesce(bayar.total, 0)
  end as sisa_tagihan
from booking b
join pelanggan p on p.id = b.pelanggan_id
join lapangan  l on l.id = b.lapangan_id
left join pengguna u on u.id = b.dibuat_oleh
left join (select booking_id, sum(jumlah) as total from pembayaran group by booking_id) bayar
       on bayar.booking_id = b.id;

-- Pembayaran + kode booking, pelanggan, lapangan, jadwal, pencatat
create view v_pembayaran_lengkap with (security_invoker = true) as
select pb.*, b.kode_booking, b.tanggal as tanggal_main, b.jam_mulai, b.jam_selesai,
       b.total_harga, p.nama as nama_pelanggan, l.nama as nama_lapangan, u.nama as nama_pembuat
from pembayaran pb
join booking   b on b.id = pb.booking_id
join pelanggan p on p.id = b.pelanggan_id
join lapangan  l on l.id = b.lapangan_id
left join pengguna u on u.id = pb.dibuat_oleh;

-- Pembelian paket + nama pelanggan, nama paket, sisa jam
create view v_pembelian_paket_lengkap with (security_invoker = true) as
select pp.*,
       p.nama        as nama_pelanggan,
       pm.nama_paket as nama_paket,
       pp.jam_total - pp.jam_terpakai                                as sisa_jam,
       (pp.tanggal_kadaluarsa < (now() at time zone 'Asia/Jakarta')::date) as kadaluarsa
from pembelian_paket pp
join pelanggan    p  on p.id  = pp.pelanggan_id
join paket_member pm on pm.id = pp.paket_id;

-- Sewa peralatan + nama peralatan, kode booking, nama pelanggan
create view v_sewa_lengkap with (security_invoker = true) as
select s.*,
       per.nama  as nama_peralatan,
       per.jenis as jenis_peralatan,
       b.kode_booking,
       p.nama    as nama_pelanggan
from sewa_peralatan s
join peralatan per on per.id = s.peralatan_id
join booking   b   on b.id   = s.booking_id
join pelanggan p   on p.id   = b.pelanggan_id;

-- Jurnal lengkap: header + detail + nama akun + pembuat
-- (dipakai Jurnal Umum & Buku Besar)
create view v_jurnal_lengkap with (security_invoker = true) as
select jd.id,
       j.id        as jurnal_id,
       j.tanggal,
       j.no_bukti,
       j.keterangan,
       j.sumber,
       jd.akun_kode,
       a.nama      as nama_akun,
       a.kategori,
       a.saldo_normal,
       jd.debit,
       jd.kredit,
       u.nama      as nama_pembuat
from jurnal_detail jd
join jurnal j on j.id   = jd.jurnal_id
join akun   a on a.kode = jd.akun_kode
left join pengguna u on u.id = j.dibuat_oleh;

-- Mutasi per akun per hari per sumber transaksi (ringkasan di server, bukan di browser).
-- Dipakai Dashboard, Laporan, dan saldo awal Buku Besar.
-- Kolom sumber dipakai Laporan untuk memisahkan penerimaan dari pelanggan
-- dengan perpindahan dana internal (settlement QRIS -> Bank).
create view v_mutasi_harian with (security_invoker = true) as
select j.tanggal, jd.akun_kode, a.nama as nama_akun, a.kategori, a.saldo_normal, j.sumber,
       sum(jd.debit) as debit, sum(jd.kredit) as kredit
from jurnal_detail jd
join jurnal j on j.id   = jd.jurnal_id
join akun   a on a.kode = jd.akun_kode
group by j.tanggal, jd.akun_kode, a.nama, a.kategori, a.saldo_normal, j.sumber;

-- Booking yang sudah lewat jadwal tetapi belum dituntaskan:
--   perlu_diselesaikan : lunas, jam main sudah lewat -> pendapatan belum diakui
--   belum_lunas        : menunggu/dp, jam main sudah lewat -> perlu ditagih/dibatalkan
create view v_booking_perlu_tindakan with (security_invoker = true) as
select b.id, b.kode_booking, b.tanggal, b.jam_mulai, b.jam_selesai, b.status,
       b.total_harga, b.pembelian_paket_id, p.nama as nama_pelanggan, l.nama as nama_lapangan,
       case when b.status = 'lunas' then 'perlu_diselesaikan' else 'belum_lunas' end as tindakan
from booking b
join pelanggan p on p.id = b.pelanggan_id
join lapangan  l on l.id = b.lapangan_id
where b.status in ('menunggu', 'dp', 'lunas')
  and (b.tanggal + b.jam_selesai) <= (now() at time zone 'Asia/Jakarta');

-- Riwayat status booking + nama pengguna
create view v_riwayat_status with (security_invoker = true) as
select r.*, b.kode_booking, u.nama as nama_pengguna
from riwayat_status_booking r
join booking b on b.id = r.booking_id
left join pengguna u on u.id = r.oleh;

-- Periode yang sedang ditutup + nama penutupnya
create view v_tutup_buku with (security_invoker = true) as
select t.*, u.nama as nama_pengguna
from tutup_buku t
left join pengguna u on u.id = t.ditutup_oleh;

-- Riwayat tutup / buka kembali + nama pengguna
create view v_riwayat_tutup_buku with (security_invoker = true) as
select r.*, u.nama as nama_pengguna
from riwayat_tutup_buku r
left join pengguna u on u.id = r.oleh;

-- Settlement QRIS + nama pencatat
create view v_settlement_qris with (security_invoker = true) as
select s.*, u.nama as nama_pembuat
from settlement_qris s
left join pengguna u on u.id = s.dibuat_oleh;

-- Ringkasan Saldo QRIS (bahan rekonsiliasi):
--   saldo_belum_cair    : uang QRIS yang belum dicairkan penyedia ke Bank
--   belum_cair_sejak    : tanggal penerimaan QRIS tertua yang belum cair
--                         (dihitung FIFO: penerimaan terlama dianggap cair lebih dulu)
--   settlement_terakhir : tanggal pencairan terakhir
create view v_ringkasan_qris with (security_invoker = true) as
with masuk as (
  select j.tanggal, sum(jd.debit) as debit
  from jurnal_detail jd join jurnal j on j.id = jd.jurnal_id
  where jd.akun_kode = '1-103' and jd.debit > 0
  group by j.tanggal
),
kumulatif as (
  select tanggal, sum(debit) over (order by tanggal) as total_kumulatif from masuk
),
keluar as (
  select coalesce(sum(kredit), 0) as total from jurnal_detail where akun_kode = '1-103'
)
select
  (select coalesce(sum(debit), 0) from masuk) - (select total from keluar)          as saldo_belum_cair,
  (select min(k.tanggal) from kumulatif k, keluar
    where k.total_kumulatif > keluar.total)                                         as belum_cair_sejak,
  (select max(tanggal) from settlement_qris)                                        as settlement_terakhir;


-- =====================================================================
--  F. KEAMANAN: Row Level Security (RLS)
--  - Pengunjung TANPA LOGIN (anon): tidak punya akses sama sekali.
--  - Pengguna login yang terdaftar di tabel pengguna:
--      * owner & admin : baca semua, catat transaksi operasional
--      * owner saja    : ubah master (lapangan, paket, peralatan)
--  - Jurnal, akun, riwayat: HANYA BACA (isinya dibuat trigger).
--  - Tidak ada izin DELETE: transaksi dibatalkan lewat status, bukan dihapus
--    (jejak audit harus tetap ada).
-- =====================================================================

alter table pengguna               enable row level security;
alter table lapangan               enable row level security;
alter table pelanggan              enable row level security;
alter table paket_member           enable row level security;
alter table akun                   enable row level security;
alter table peralatan              enable row level security;
alter table pembelian_paket        enable row level security;
alter table booking                enable row level security;
alter table pembayaran             enable row level security;
alter table sewa_peralatan         enable row level security;
alter table riwayat_status_booking enable row level security;
alter table jurnal                 enable row level security;
alter table jurnal_detail          enable row level security;
alter table tutup_buku             enable row level security;
alter table riwayat_tutup_buku     enable row level security;
alter table settlement_qris        enable row level security;

-- Hak akses dasar (GRANT). anon dicabut seluruhnya.
-- Supabase otomatis memberi SEMUA hak (termasuk DELETE & TRUNCATE) pada tabel
-- baru, jadi hak authenticated juga dicabut dulu, lalu diberi lagi seperlunya.
revoke all on all tables in schema public from anon;
revoke all on all tables in schema public from authenticated;
grant usage on schema public to authenticated;
grant select                 on pengguna, akun, jurnal, jurnal_detail, riwayat_status_booking,
                                tutup_buku, riwayat_tutup_buku                            to authenticated;
grant select, insert, update on lapangan, pelanggan, paket_member, peralatan,
                                booking, sewa_peralatan                                   to authenticated;
grant select, insert         on pembayaran, pembelian_paket, settlement_qris              to authenticated;
grant select on v_booking_lengkap, v_pembayaran_lengkap, v_pembelian_paket_lengkap,
                v_sewa_lengkap, v_jurnal_lengkap, v_mutasi_harian,
                v_booking_perlu_tindakan, v_riwayat_status,
                v_tutup_buku, v_riwayat_tutup_buku,
                v_settlement_qris, v_ringkasan_qris                                       to authenticated;
revoke execute on function peran_saya() from public, anon;
grant  execute on function peran_saya() to authenticated;

-- Pengguna: profil sendiri + nama sesama staf (untuk kolom "dicatat oleh")
create policy "lihat pengguna" on pengguna for select to authenticated
  using (id = auth.uid() or peran_saya() is not null);

-- Master data: semua staf baca; hanya owner yang tambah/ubah
create policy "baca lapangan"  on lapangan for select to authenticated using (peran_saya() is not null);
create policy "kelola lapangan tambah" on lapangan for insert to authenticated with check (peran_saya() = 'owner');
create policy "kelola lapangan ubah"   on lapangan for update to authenticated
  using (peran_saya() = 'owner') with check (peran_saya() = 'owner');

create policy "baca paket"  on paket_member for select to authenticated using (peran_saya() is not null);
create policy "kelola paket tambah" on paket_member for insert to authenticated with check (peran_saya() = 'owner');
create policy "kelola paket ubah"   on paket_member for update to authenticated
  using (peran_saya() = 'owner') with check (peran_saya() = 'owner');

create policy "baca peralatan"  on peralatan for select to authenticated using (peran_saya() is not null);
create policy "kelola peralatan tambah" on peralatan for insert to authenticated with check (peran_saya() = 'owner');
create policy "kelola peralatan ubah"   on peralatan for update to authenticated
  using (peran_saya() = 'owner') with check (peran_saya() = 'owner');

-- Pelanggan (data pribadi): hanya staf login
create policy "baca pelanggan"   on pelanggan for select to authenticated using (peran_saya() is not null);
create policy "tambah pelanggan" on pelanggan for insert to authenticated with check (peran_saya() is not null);
create policy "ubah pelanggan"   on pelanggan for update to authenticated
  using (peran_saya() is not null) with check (peran_saya() is not null);

-- Akun, jurnal, riwayat: hanya baca
create policy "baca akun"          on akun                   for select to authenticated using (peran_saya() is not null);
create policy "baca jurnal"        on jurnal                 for select to authenticated using (peran_saya() is not null);
create policy "baca jurnal detail" on jurnal_detail          for select to authenticated using (peran_saya() is not null);
create policy "baca riwayat"       on riwayat_status_booking for select to authenticated using (peran_saya() is not null);
create policy "baca tutup buku"    on tutup_buku             for select to authenticated using (peran_saya() is not null);
create policy "baca riwayat tutup" on riwayat_tutup_buku     for select to authenticated using (peran_saya() is not null);

-- Transaksi operasional: owner & admin
create policy "baca booking"   on booking for select to authenticated using (peran_saya() is not null);
create policy "tambah booking" on booking for insert to authenticated with check (peran_saya() is not null);
create policy "ubah booking"   on booking for update to authenticated
  using (peran_saya() is not null) with check (peran_saya() is not null);

create policy "baca pembayaran"   on pembayaran for select to authenticated using (peran_saya() is not null);
create policy "tambah pembayaran" on pembayaran for insert to authenticated with check (peran_saya() is not null);

-- Settlement QRIS: semua staf baca; hanya owner yang mencatat
create policy "baca settlement"   on settlement_qris for select to authenticated using (peran_saya() is not null);
create policy "tambah settlement" on settlement_qris for insert to authenticated with check (peran_saya() = 'owner');

create policy "baca pembelian paket"   on pembelian_paket for select to authenticated using (peran_saya() is not null);
create policy "tambah pembelian paket" on pembelian_paket for insert to authenticated with check (peran_saya() is not null);

create policy "baca sewa"   on sewa_peralatan for select to authenticated using (peran_saya() is not null);
create policy "tambah sewa" on sewa_peralatan for insert to authenticated with check (peran_saya() is not null);
create policy "ubah sewa"   on sewa_peralatan for update to authenticated
  using (peran_saya() is not null) with check (peran_saya() is not null);
